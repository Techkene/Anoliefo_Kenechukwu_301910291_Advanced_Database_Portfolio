"""
AquaSense+ | Portfolio 2 | Before/after optimisation benchmark

What it does
  1. Drops the optimisation indexes so we start from "foreign keys only".
  2. Runs every query in queries.sql 7 times (1 warm-up + 6 timed) and records
     the median, plus the full EXPLAIN (ANALYZE, BUFFERS) plan.
  3. Creates the indexes in indexes.sql, runs ANALYZE, and repeats step 2.
  4. Builds a materialized view for the cooperative dashboard (Q8) and times it.
  5. Writes plans/, results/, performance_results.md and performance_chart.png.

Usage:  python3 run_benchmark.py            (env: PGHOST, PGUSER, PGDATABASE=aquasense)
"""
import os, re, statistics, time, pathlib
import psycopg2

HERE = pathlib.Path(__file__).parent
PLANS, RESULTS = HERE / "plans", HERE / "results"
PLANS.mkdir(exist_ok=True); RESULTS.mkdir(exist_ok=True)

conn = psycopg2.connect(dbname=os.getenv("PGDATABASE", "aquasense"))
conn.autocommit = True
cur = conn.cursor()

OPT_INDEXES = ["ix_wqr_unit_time", "ix_wqr_low_oxygen", "ix_feeding_batch_cov", "ix_harvest_batch",
               "ix_batch_unit", "ix_unit_farm", "ix_mortality_batch_date"]

def load_queries():
    text = (HERE / "queries.sql").read_text()
    parts = re.split(r"^-- @(Q\d+) (.*)$", text, flags=re.M)
    return [(parts[i], parts[i + 1].strip(), parts[i + 2].strip().rstrip(";")) for i in range(1, len(parts), 3)]

def time_query(sql, runs=6):
    cur.execute(sql); cur.fetchall()                     # warm-up (fills the buffer cache)
    times = []
    for _ in range(runs):
        t = time.perf_counter(); cur.execute(sql); rows = cur.fetchall()
        times.append((time.perf_counter() - t) * 1000)
    return statistics.median(times), rows, [d[0] for d in cur.description]

def plan(sql):
    cur.execute("EXPLAIN (ANALYZE, BUFFERS, COSTS) " + sql)
    return "\n".join(r[0] for r in cur.fetchall())

def summary(plan_text):
    """Return the distinct scan types used and the shared buffers touched by the top node."""
    pat = r"(Seq Scan|Index Only Scan|Index Scan|Bitmap Heap Scan|Bitmap Index Scan)(?: Backward)?(?: using (\w+))? on (\w+)"
    seen = []
    for kind, ix, tbl in re.findall(pat, plan_text):
        s = f"{kind} on {tbl}" + (f" ({ix})" if ix else "")
        if s not in seen: seen.append(s)
    m = re.search(r"Buffers: shared hit=(\d+)(?: read=(\d+))?", plan_text)
    buf = (int(m.group(1)) + int(m.group(2) or 0)) if m else 0
    return "; ".join(seen[:3]), buf

def phase(label, queries):
    out = {}
    for qid, title, sql in queries:
        ms, rows, cols = time_query(sql)
        p = plan(sql)
        (PLANS / f"{qid}_{label}.txt").write_text(f"-- {qid}: {title}\n-- phase: {label}\n\n{sql}\n\n{p}\n")
        if label == "before":
            with open(RESULTS / f"{qid}_result.txt", "w") as f:
                f.write(f"-- {qid}: {title}\n-- {len(rows)} row(s); first 15 shown\n\n")
                f.write(" | ".join(cols) + "\n")
                for r in rows[:15]: f.write(" | ".join(str(v) for v in r) + "\n")
        access, buf = summary(p)
        out[qid] = dict(title=title, ms=ms, rows=len(rows), access=access, buffers=buf)
        print(f"{label:6} {qid}  {ms:9.2f} ms  {access}")
    return out

queries = load_queries()
cur.execute("SET search_path TO aqua")
for ix in OPT_INDEXES: cur.execute(f"DROP INDEX IF EXISTS aqua.{ix}")
cur.execute("DROP MATERIALIZED VIEW IF EXISTS aqua.mv_state_monthly_sales")
cur.execute("ANALYZE")
before = phase("before", queries)

cur.execute((HERE / "indexes.sql").read_text())
after = phase("after", queries)

# ---- Q8 alternative: materialized view for the cooperative dashboard ----
q8_sql = dict((q[0], q[2]) for q in queries)["Q8"]
cur.execute("CREATE MATERIALIZED VIEW aqua.mv_state_monthly_sales AS " + q8_sql.replace("WHERE s.sold_on >= DATE '2026-01-01'", ""))
cur.execute("CREATE UNIQUE INDEX ON aqua.mv_state_monthly_sales (state_code, month)")
t = time.perf_counter(); cur.execute("REFRESH MATERIALIZED VIEW CONCURRENTLY aqua.mv_state_monthly_sales"); refresh_ms = (time.perf_counter() - t) * 1000
mv_sql = "SELECT * FROM aqua.mv_state_monthly_sales WHERE month >= DATE '2026-01-01' ORDER BY state_code, month"
mv_ms, _, _ = time_query(mv_sql)
(PLANS / "Q8_materialized_view.txt").write_text(mv_sql + "\n\n" + plan(mv_sql) + f"\n\n-- REFRESH CONCURRENTLY took {refresh_ms:.1f} ms\n")

# ---- index sizes ----
cur.execute("""SELECT indexrelname, pg_size_pretty(pg_relation_size(indexrelid)), relname
               FROM pg_stat_user_indexes WHERE schemaname='aqua' AND indexrelname = ANY(%s)
               ORDER BY pg_relation_size(indexrelid) DESC""", (OPT_INDEXES,))
sizes = cur.fetchall()

# ---- report ----
lines = ["# Performance results (generated by run_benchmark.py)\n",
         f"PostgreSQL {conn.server_version // 10000}, median of 6 warm runs, client-side wall time. Buffers = 8 kB pages touched by the plan (from EXPLAIN BUFFERS).\n",
         "| Query | Purpose | Rows | Before (ms) | Buffers before | Access path before | After (ms) | Buffers after | Access path after | Speed-up |",
         "|---|---|---|---|---|---|---|---|---|---|"]
for qid, _, _ in queries:
    b, a = before[qid], after[qid]
    lines.append(f"| {qid} | {b['title']} | {b['rows']} | {b['ms']:.2f} | {b['buffers']:,} | {b['access']} | {a['ms']:.2f} | {a['buffers']:,} | {a['access']} | {b['ms']/a['ms']:.1f}x |")
lines += ["", f"**Q8 via materialized view:** {mv_ms:.2f} ms (vs {after['Q8']['ms']:.2f} ms live); "
              f"`REFRESH MATERIALIZED VIEW CONCURRENTLY` cost {refresh_ms:.1f} ms.", "",
          "## Index sizes", "", "| Index | Table | Size |", "|---|---|---|"]
lines += [f"| {n} | {t} | {s} |" for n, s, t in sizes]
(HERE / "performance_results.md").write_text("\n".join(lines) + "\n")

# ---- chart ----
import matplotlib; matplotlib.use("Agg")
import matplotlib.pyplot as plt
ids = [q[0] for q in queries]
fig, ax = plt.subplots(figsize=(10, 4.8))
x = range(len(ids)); w = 0.38
ax.bar([i - w/2 for i in x], [before[i]["ms"] for i in ids], w, label="Before (FK only)", color="#c9d6e3")
ax.bar([i + w/2 for i in x], [after[i]["ms"] for i in ids], w, label="After optimisation", color="#0b3a5c")
ax.set_yscale("log"); ax.set_xticks(list(x)); ax.set_xticklabels(ids)
ax.set_ylabel("Median execution time (ms, log scale)")
ax.set_title("AquaSense+ query performance before vs after indexing")
for s in ("top", "right"): ax.spines[s].set_visible(False)
ax.legend(frameon=False); fig.tight_layout(); fig.savefig(HERE / "performance_chart.png", dpi=140)
print("\nWritten performance_results.md, performance_chart.png, plans/, results/")
